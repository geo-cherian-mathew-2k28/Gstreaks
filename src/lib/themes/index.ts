export const DEFAULT_THEME_ID = 'tokyo-night';

export function getTheme(themeId?: string): ThemePalette {
  if (!themeId) return THEMES[DEFAULT_THEME_ID];
  const normalized = themeId.toLowerCase().trim().replace(/_/g, '-');
  return THEMES[normalized] || THEMES[DEFAULT_THEME_ID];
}
